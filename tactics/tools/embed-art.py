#!/usr/bin/env python3
"""Embed the portrait PNGs in tactics/art/ into index.html as data URIs.

The phone app's artifact viewer does not reliably load images by relative
path, so every image the game uses is inlined between the ART markers.
Run from anywhere: python3 tactics/tools/embed-art.py
"""
import base64, pathlib, re, json

ROOT = pathlib.Path(__file__).resolve().parent.parent
ART = {  # key in window.RAE_ART  ->  file in tactics/art/
    "front": "rae-portrait.png",   # front-facing portrait (panel, dialogue, title)
    "side": "rae-battle.png",      # side-on battle pose, faces right
}
data = {k: "data:image/png;base64," + base64.b64encode((ROOT / "art" / f).read_bytes()).decode() for k, f in ART.items()}
block = "<!-- ART:BEGIN (generated by tools/embed-art.py, do not edit) -->\n<script>window.RAE_ART=" + json.dumps(data) + ";</script>\n<!-- ART:END -->"
html = (ROOT / "index.html").read_text()
html, n = re.subn(r"<!-- ART:BEGIN.*?<!-- ART:END -->", lambda m: block, html, flags=re.S)
assert n == 1, "ART markers not found in index.html"
(ROOT / "index.html").write_text(html)
print("embedded", ", ".join(f"{k} ({len(v)//1024} KB)" for k, v in data.items()))
